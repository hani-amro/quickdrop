import { describe, expect, it } from "vitest";
import { localDateSeries } from "./analytics.js";

// §15 — وحدات: منطق صافٍ فقط (بناء سلسلة الأيام). لا اتصال قاعدة.
// §16.8 — التقويم بمنطقة المستأجر؛ هذه الدالة تبني الأيام التقويمية المتصلة للرسم.

describe("localDateSeries — سلسلة أيام متصلة تنتهي باليوم", () => {
  it("تنتج days تواريخ متتالية، الأقدم→الأحدث، آخرها اليوم", () => {
    expect(localDateSeries("2026-07-12", 7)).toEqual([
      "2026-07-06",
      "2026-07-07",
      "2026-07-08",
      "2026-07-09",
      "2026-07-10",
      "2026-07-11",
      "2026-07-12",
    ]);
  });

  it("يعبر حدود الشهر بشكل تقويمي صحيح", () => {
    expect(localDateSeries("2026-03-02", 4)).toEqual(["2026-02-27", "2026-02-28", "2026-03-01", "2026-03-02"]);
  });

  it("يعبر حدود السنة", () => {
    expect(localDateSeries("2026-01-01", 3)).toEqual(["2025-12-30", "2025-12-31", "2026-01-01"]);
  });

  it("يوم واحد = اليوم وحده", () => {
    expect(localDateSeries("2026-07-12", 1)).toEqual(["2026-07-12"]);
  });

  it("الطول يساوي days دائماً", () => {
    expect(localDateSeries("2026-07-12", 30)).toHaveLength(30);
  });
});
